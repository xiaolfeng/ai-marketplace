import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EDITORIAL_COMPONENTS } from "./editorial.mjs";
import { REPLAY_COMPONENTS } from "./replay.mjs";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
export const PRESETS = {
  editorial: "plugins/html/skills/editorial-report",
  "replay-self": "plugins/replay/skills/replay-html",
  "replay-public": "plugins/replay/skills/replay-post-html",
};

function bundle(preset) {
  const modules = new Map();
  const externals = new Set();
  const add = (name) => {
    if (modules.has(name)) return;
    modules.set(name, "");
    let source = fs.readFileSync(
      path.join(ROOT, "scripts/xsu", `${name}.mjs`),
      "utf8",
    );
    source = source.replace(
      /^import\s+([\s\S]*?)\s+from\s+["']([^"']+)["'];?\s*$/gm,
      (_, binding, specifier) => {
        const object = specifier.startsWith("node:")
          ? (externals.add(specifier),
            `__external[${JSON.stringify(specifier)}]`)
          : (() => {
              if (!/^\.\/[a-z-]+\.mjs$/.test(specifier))
                throw new Error(`Unsupported bundle import: ${specifier}`);
              const dependency = specifier.slice(2, -4);
              add(dependency);
              return `__require(${JSON.stringify(dependency)})`;
            })();
        const clean = binding.trim();
        if (clean.startsWith("{"))
          return `const ${clean.replace(/\bas\b/g, ":")} = ${object};\n`;
        if (clean.startsWith("* as "))
          return `const ${clean.slice(5)} = ${object};\n`;
        return `const ${clean} = ${object}.default;\n`;
      },
    );
    const names = [];
    source = source.replace(
      /^export\s+(?=(?:function|class|const|let)\s)(function|class|const|let)\s+([A-Za-z_$][\w$]*)/gm,
      (_, kind, exported) => {
        names.push(exported);
        return `${kind} ${exported}`;
      },
    );
    source = source.replace(/^export\s*\{([^}]+)\};?\s*$/gm, (_, exports) => {
      for (const item of exports
        .split(",")
        .map((value) => value.trim())
        .filter(Boolean)) {
        if (!/^[A-Za-z_$][\w$]*$/.test(item))
          throw new Error(`Unsupported bundle export: ${item}`);
        names.push(item);
      }
      return "";
    });
    if (/^\s*(?:import|export)\s/m.test(source))
      throw new Error(`Unsupported module syntax in ${name}`);
    modules.set(name, `${source}\nreturn {${names.join(",")}};`);
  };
  const adapter = preset === "editorial" ? "editorial" : "replay";
  add("cli");
  add(adapter);
  const imports = [...externals]
    .sort()
    .map((name, i) => `import * as __e${i} from ${JSON.stringify(name)};`)
    .join("\n");
  const external = [...externals]
    .sort()
    .map((name, i) => `${JSON.stringify(name)}:__e${i}`)
    .join(",");
  const factories = [...modules]
    .map(
      ([name, source]) =>
        `${JSON.stringify(name)}: (__require) => {\n${source}\n}`,
    )
    .join(",\n");
  const assets = {
    preset,
    template: fs.readFileSync(
      path.join(ROOT, PRESETS[preset], "references/template.html"),
      "utf8",
    ),
  };
  const wiring =
    preset === "editorial"
      ? "{validate: implementation.validateEditorial, render: implementation.renderEditorial, components: implementation.EDITORIAL_COMPONENTS}"
      : "{validate: implementation.validateReplay, render: implementation.lowerReplay, migrate: implementation.migrateReplay, components: implementation.REPLAY_COMPONENTS}";
  return `#!/usr/bin/env node\n// Generated by scripts/xsu/build.mjs. Do not edit.\n${imports}\nconst __external={${external}};\nconst __factories={${factories}};\nconst __cache=Object.create(null);\nconst __require=(id)=>__cache[id]||(__cache[id]=__factories[id](__require));\nconst implementation=__require(${JSON.stringify(adapter)});\nconst assets=${JSON.stringify(assets)};\nprocess.exitCode=__require("cli").runCli(process.argv.slice(2),assets,${wiring});\n`;
}

export function buildAll(check = false) {
  const outputs = new Map();
  for (const [preset, skill] of Object.entries(PRESETS)) {
    outputs.set(path.join(ROOT, skill, "scripts/xsu.mjs"), bundle(preset));
    outputs.set(
      path.join(ROOT, skill, "examples/example.xsu"),
      `// Generated from scripts/xsu/fixtures/${preset}.xsu; do not edit.\n${fs.readFileSync(path.join(ROOT, "scripts/xsu/fixtures", `${preset}.xsu`), "utf8")}`,
    );
    const registry =
      preset === "editorial" ? EDITORIAL_COMPONENTS : REPLAY_COMPONENTS;
    outputs.set(
      path.join(ROOT, skill, "references/xsu-components.json"),
      `${JSON.stringify({ preset, components: registry }, null, 2)}\n`,
    );
    if (preset !== "editorial") {
      for (const name of [
        "reverse-methodology.md",
        "step-chain-schema.md",
        "audience-voice.md",
      ]) {
        outputs.set(
          path.join(ROOT, skill, "references/xsu-shared", name),
          `<!-- Generated from plugins/replay/skills/_shared/${name}; do not edit. -->\n\n${fs.readFileSync(path.join(ROOT, "plugins/replay/skills/_shared", name), "utf8")}`,
        );
      }
    }
  }
  let drift = false;
  for (const [target, content] of outputs) {
    const current = fs.existsSync(target)
      ? fs.readFileSync(target, "utf8")
      : null;
    if (current === content) continue;
    if (check) {
      console.error(`XSU distribution differs: ${path.relative(ROOT, target)}`);
      drift = true;
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
      console.log(`Built ${path.relative(ROOT, target)}`);
    }
  }
  return !drift;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check")) {
    console.error("Usage: node scripts/xsu/build.mjs [--check]");
    process.exitCode = 1;
  } else process.exitCode = buildAll(args.includes("--check")) ? 0 : 1;
}
